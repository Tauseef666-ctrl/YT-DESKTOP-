package net.newpipe.app.component

import androidx.compose.material3.ExperimentalMaterial3Api
import androidx.compose.material3.PlainTooltip
import androidx.compose.material3.Text
import androidx.compose.material3.TooltipBox
import androidx.compose.material3.TooltipDefaults
import androidx.compose.material3.rememberTooltipState
import androidx.compose.runtime.Composable
import androidx.compose.ui.Modifier

/**
 * Wraps [content] with a plain tooltip shown on hover/focus. Use for icon-only controls so their
 * purpose is discoverable by pointer and keyboard users alike.
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun PlusTooltip(
    text: String,
    modifier: Modifier = Modifier,
    content: @Composable () -> Unit
) {
    TooltipBox(
        positionProvider = TooltipDefaults.rememberPlainTooltipPositionProvider(),
        tooltip = { PlainTooltip { Text(text = text) } },
        state = rememberTooltipState(),
        modifier = modifier,
        content = content
    )
}
